"""Regenerate site/assets/pubs.js from the CV's LaTeX source.

    python3 tools/cv2pubs.py path/to/cv.tex

Reads every tagged \\cvitem in the CV's Publications section. Links already in
pubs.js are kept (matched by title); arXiv entries get their arXiv link
automatically. Add code/demo/weights links, or a link for a newly published
paper, by editing pubs.js afterwards.
"""
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "site" / "assets" / "pubs.js"
PREFIX = "// Generated by tools/cv2pubs.py from the CV; safe to edit by hand.\nwindow.PUBS = "


def load_existing():
    if not OUT.exists():
        return {}
    text = OUT.read_text(encoding="utf-8")
    data = json.loads(text[text.index("["):text.rindex("]") + 1])
    return {p["title"]: p for p in data}


def parse(tex):
    sec = tex[tex.index("\\section{Publications}"):tex.index("\\section{Patents}")]
    old = load_existing()
    pubs = []
    for line in sec.split("\n"):
        if not line.startswith("\\cvitem{}{\\tag"):
            continue
        body = line.rstrip()[len("\\cvitem{}{"):-1]  # drop the \cvitem wrapper's closing brace
        tags = [t for t in re.findall(r"\\tag(\w+)\{", body) if t != "Award"]
        body = re.sub(r"\\tagAward\{\\textbf\{Award\\twemoji\{trophy\}\}\}", "", body)
        body = re.sub(r"\\tag\w+\{\w+\}", "", body)
        authors, rest = body.split("\\textit{``", 1)
        title, venue = rest.split("''}", 1)
        authors = authors.replace("\\textsuperscript{*}", "*")
        authors = re.sub(r"\\textbf\{([^}]*)\}", r"\1", authors).strip().rstrip(",")
        venue = venue.strip().lstrip(",").strip()
        award = "Best Student Paper Award" if "[Best Student Paper Award]" in venue else None
        venue = re.sub(r",?\s*\\textbf\{\[Best Student Paper Award\]\}", "", venue).rstrip(".}").strip()
        venue = venue.replace("Interspeech 2024 ASVSpoof Challenge", "ASVspoof 2024 Workshop")
        arxiv = re.search(r"arXiv:(\d{2})(\d{2})\.\d+", venue)
        years = re.findall(r"20\d\d", venue)
        year = int(years[-1]) if years else 2000 + int(arxiv.group(1))
        if arxiv and not years:
            venue += f", {year}"
        if venue.startswith("under review"):
            venue = re.sub(r",\s*20\d\d$", "", venue)
        links = dict(old.get(title, {}).get("links", {}))
        if arxiv and "paper" not in links:
            links["paper"] = "https://arxiv.org/abs/" + re.search(r"arXiv:([\d.]+)", venue).group(1).rstrip(".")
        pubs.append({
            "title": title,
            "authors": [a.strip() for a in authors.split(",")],
            "venue": venue,
            "year": year,
            "status": "preprint" if ("arXiv" in venue or "under review" in venue) else "published",
            "tags": tags,
            "award": award,
            "first": authors.startswith("Jihwan Lee"),
            "links": links,
        })
    pubs.sort(key=lambda p: -p["year"])  # stable: keeps the CV's order within a year
    return pubs


if __name__ == "__main__":
    pubs = parse(Path(sys.argv[1]).read_text(encoding="utf-8"))
    OUT.write_text(PREFIX + json.dumps(pubs, indent=1, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(pubs)} papers; without links: {[p['title'][:50] for p in pubs if not p['links']]})")
